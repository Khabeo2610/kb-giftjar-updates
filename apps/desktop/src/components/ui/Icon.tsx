/** Icon dành cho người dùng chọn trên nút Stream Deck. */
export const DECK_ICON_CHOICES = Object.keys(ICONS).filter(
  (n) => !['House', 'LayoutGrid', 'Gamepad2', 'Bot', 'MessageCircleHeart', 'MonitorPlay', 'Layers', 'Settings'].includes(n),
);

export function Icon({ name, ...props }: { name: string } & LucideProps) {
  const Cmp = ICONS[name] ?? Sparkles;
  return <Cmp aria-hidden="true" {...props} />;
}
